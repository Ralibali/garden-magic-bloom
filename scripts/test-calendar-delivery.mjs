import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const load = name => readFile(new URL('../supabase/migrations/' + name, import.meta.url), 'utf8');
await db.exec(`create role anon; create role authenticated; create role service_role;
create schema auth; create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('request.test_user',true),'')::uuid $$;
create table public.profiles(user_id uuid primary key,preferences jsonb);
create table public.suppressed_emails(email text primary key);
create table public.email_unsubscribe_tokens(email text primary key,token text);
create table public.email_send_log(message_id text,template_name text,recipient_email text,status text);
create table public.test_queue(payload jsonb);
create function public.enqueue_email(queue_name text,payload jsonb) returns void language sql as $$ insert into public.test_queue values ($2) $$;`);
await db.exec(await load('20260426120000_create_public_leads.sql'));
await db.exec(await load('20261111162633_spring_calendar_delivery.sql'));
const plan={type:'sakalender',season:2027,zone:'6',method:'Växthus',crops:['Tomat','Rädisa'],varieties:{Tomat:'Sungold'}};
const request=(value,pilot=false) => db.query('select public.request_sowing_calendar($1,$2,false,$3) as result',['odlare@example.se',JSON.stringify(value),pilot]);
await db.exec('set role anon');
assert.equal((await request(plan)).rows[0].result,'accepted');
assert.equal((await request(plan,true)).rows[0].result,'accepted');
await assert.rejects(db.query('select email from public.public_leads'));
await assert.rejects(request({...plan,zone:'0'}));
await db.exec('reset role');
const {rows}=await db.query('select payload from public.test_queue');
assert.equal(rows.length,1);
const url=new URL(rows[0].payload.html.match(/href="([^"]+#plan=[^"]+)"/)[1]);
assert.deepEqual(JSON.parse(Buffer.from(url.hash.slice(6),'base64url').toString()),plan);
assert.ok(rows[0].payload.text.includes(url.href));
assert.ok(rows[0].payload.unsubscribe_token);
assert.deepEqual((await db.query('select pilot_opt_in,consent_marketing from public.public_leads')).rows,[{pilot_opt_in:true,consent_marketing:false}]);
await db.exec('alter table public.test_queue add constraint simulate_queue_failure check(false) not valid');
await assert.rejects(request({...plan,zone:'5'}));
assert.equal((await db.query('select count(*) n from public.public_leads')).rows[0].n,1);
await db.close();
console.log('Calendar email, portable link, optional pilot, duplicate and rollback verified.');
