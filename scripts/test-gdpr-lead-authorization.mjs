import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const require = createRequire(new URL('../package.json', import.meta.url));
const { PGlite } = require('@electric-sql/pglite');
const db = new PGlite();
const uid = '12345678-abcd-4abc-abcd-123456789012', other = '23456789-abcd-4abc-abcd-123456789012';
await db.exec(`create role anon; create role authenticated; create schema auth;
create table auth.users (id uuid primary key, email text, email_confirmed_at timestamptz);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.user_id', true), '')::uuid $$;
create table public.public_leads(id uuid default gen_random_uuid(), email text, consent_marketing boolean default true, converted_user_id uuid, converted_at timestamptz);
insert into auth.users values ('${uid}', 'owner@example.se', now()), ('${other}', 'other@example.se', null);
insert into public.public_leads(email) values ('owner@example.se'), ('other@example.se');`);
const migration = await readFile(new URL('../supabase/migrations/20260930213336_gdpr_public_lead_authorization.sql', import.meta.url), 'utf8');
await db.exec(migration);
await db.exec('set role anon');
await assert.rejects(() => db.query(`select public.mark_public_leads_converted('owner@example.se','${uid}')`), /permission denied/);
await db.exec('reset role; set role authenticated');
await db.query(`select set_config('request.user_id',$1,false)`, [uid]);
await assert.rejects(() => db.query(`select public.mark_public_leads_converted('owner@example.se','${other}')`), /Unauthorized/);
await assert.rejects(() => db.query(`select public.mark_public_leads_converted('other@example.se','${uid}')`), /Verified email required/);
assert.equal((await db.query(`select public.mark_public_leads_converted('owner@example.se','${uid}') as count`)).rows[0].count, 1);
assert.equal((await db.query(`select public.mark_public_leads_converted('owner@example.se','${uid}') as count`)).rows[0].count, 0);
await db.query(`select set_config('request.user_id',$1,false)`, [other]);
await assert.rejects(() => db.query(`select public.mark_public_leads_converted('other@example.se','${other}')`), /Verified email required/);
await db.exec('reset role');
const inserted = await db.query("insert into public.public_leads(email) values('new@example.se') returning consent_marketing");
assert.equal(inserted.rows[0].consent_marketing, false);
await db.close();
console.log('Garden lead authorization verified: anonymous/other-account/unconfirmed requests denied, own confirmed match succeeds, missing marketing choice remains false.');
