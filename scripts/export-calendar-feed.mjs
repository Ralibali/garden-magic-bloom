// Bygger en fristående kopia av src/lib/gardenCalendar.ts (med såmatrisen och
// grödidentiteten) åt edge functionen calendar-feed, så att prenumerationen och
// appen räknar fram exakt samma datum. Kör efter ändringar i kalenderlogiken:
//   node scripts/export-calendar-feed.mjs
// src/test/calendarFeedBundle.test.ts larmar om kopian är inaktuell.
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
// esbuild följer med vite och finns därför alltid i node_modules.
import { build } from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const OUTPUT_PATH = path.join(root, 'supabase/functions/_shared/gardenCalendar.bundle.js')

const HEADER = `// Auto-generated by scripts/export-calendar-feed.mjs from src/lib/gardenCalendar.ts.
// Do not edit by hand – change the source and run the script again.
`

export async function bundleCalendarFeed() {
  const result = await build({
    entryPoints: [path.join(root, 'src/lib/gardenCalendar.ts')],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    legalComments: 'none',
    charset: 'utf8',
    alias: { '@': path.join(root, 'src') },
    logLevel: 'silent',
  })
  // Relativa sökvägar i esbuilds kommentarer så att utdata inte beror på var repot ligger.
  const code = result.outputFiles[0].text.replaceAll(`${root}/`, '')
  return HEADER + code
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await fs.writeFile(OUTPUT_PATH, await bundleCalendarFeed())
  console.log(`Wrote ${path.relative(root, OUTPUT_PATH)}`)
}
