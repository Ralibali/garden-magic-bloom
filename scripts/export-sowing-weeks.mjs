import fs from 'node:fs/promises'
import path from 'node:path'
import ts from 'typescript'

const root = process.cwd()
const sourcePath = path.join(root, 'src/data/sowingMatrix.ts')
const outputPath = path.join(root, 'supabase/functions/_shared/sowingWeeks.ts')

const source = await fs.readFile(sourcePath, 'utf8')
const compiled = ts.transpileModule(source, {
  compilerOptions: {
    module: ts.ModuleKind.CommonJS,
    target: ts.ScriptTarget.ES2020,
  },
}).outputText

const module = { exports: {} }
const exports = module.exports
new Function('module', 'exports', compiled)(module, exports)

const matrix = module.exports.sowingMatrix
if (!Array.isArray(matrix)) {
  throw new Error('Could not read exported sowingMatrix')
}

const exported = {}
for (const crop of matrix) {
  exported[crop.name] = {}
  for (const [zone, timing] of Object.entries(crop.zones ?? {})) {
    exported[crop.name][zone] = {
      pre: timing.preStart == null || timing.preEnd == null ? null : [timing.preStart, timing.preEnd],
      out: timing.plantOutStart == null || timing.plantOutEnd == null ? null : [timing.plantOutStart, timing.plantOutEnd],
      direct: timing.directSowStart == null || timing.directSowEnd == null ? null : [timing.directSowStart, timing.directSowEnd],
      harvest: timing.harvestStart == null || timing.harvestEnd == null ? null : [timing.harvestStart, timing.harvestEnd],
    }
  }
}

const body = `// Auto-generated by scripts/export-sowing-weeks.mjs from src/data/sowingMatrix.ts.
// Run the script whenever sowingMatrix.ts changes.

export type WeekRange = [number, number]

export interface SowingWeekTiming {
  pre: WeekRange | null
  out: WeekRange | null
  direct: WeekRange | null
  harvest: WeekRange | null
}

export const sowingWeeks = ${JSON.stringify(exported, null, 2)} as const satisfies Record<string, Record<string, SowingWeekTiming>>

export function normalizeZone(zone: unknown): number {
  const parsed = Number.parseInt(String(zone ?? ''), 10)
  return Number.isFinite(parsed) && parsed >= 1 && parsed <= 8 ? parsed : 3
}

export function getSowingWeekTiming(cropName: string, zone: unknown): SowingWeekTiming | null {
  const normalizedZone = String(normalizeZone(zone))
  return sowingWeeks[cropName as keyof typeof sowingWeeks]?.[normalizedZone] ?? null
}
`

await fs.writeFile(outputPath, body, 'utf8')
console.log(`Wrote ${path.relative(root, outputPath)}`)
